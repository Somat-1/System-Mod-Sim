#!/usr/bin/env python3
"""The RMT run: did the step-timing fix work, and does it now saturate?

Two questions at once, because fixing the first created the second. With the
step train generated by the RMT peripheral instead of a CPU busy-wait, the
stage finally runs near its commanded speed - and 8 mm/s commanded is close
enough to the 8.333 mm/s AquadB ceiling that the velocity ripple starts
touching it.

No terminal log was kept for this run, so the profiles are grouped by their
own measured speed rather than read from DIAG records. The groups are
unambiguous (2.0 / 4.9 / 7.6 mm/s, well separated), but the per-move pulse
counts that would give the timing fit directly are not available.

Writes plots/temp/06_rmt_bandwidth.{png,pdf}.
"""
from pathlib import Path
import os
import sys

import numpy as np
import matplotlib.pyplot as plt

_HERE = Path(__file__).resolve().parent
_MOTOR = _HERE.parent.parent.parent / "motor identification" / "scripts"
if str(_MOTOR) not in sys.path:
    sys.path.insert(0, str(_MOTOR))
from staircase_figures import INK, INK2, INK3, SURFACE, GRID, style   # noqa

SRC = Path(os.environ.get("RMT_CSV", _HERE.parent.parent / "RMT_BW_Test.csv"))
OUT = Path(os.environ.get("ISO_TEMP_OUT", _HERE / "plots" / "temp"))
HEADER_ROWS = 23
WRAP = 2 ** 32
CEIL_NM = 8333.0                 # 120 ns AquadB at 1 nm per increment
OLD_SRC = SRC.parent / "PLC_Bandwidth_test.csv"   # the CPU-timed firmware
COLOUR = {2.0: "#5f8bc5", 5.0: "#c88e5c", 8.0: "#99483e"}
RED, GREEN = "#99483e", "#356449"


def load(path=SRC):
    idx, val = [], []
    with path.open(encoding="utf-8", errors="replace") as fh:
        for i, line in enumerate(fh):
            if i < HEADER_ROWS:
                continue
            line = line.strip()
            if not line or line.startswith("EOF"):
                continue
            q = line.split("\t")
            if len(q) == 2:
                idx.append(int(q[0]))
                val.append(int(q[1]))
    val = np.array(val, np.int64)
    d = np.diff(val)
    d[d > WRAP // 2] -= WRAP
    d[d < -WRAP // 2] += WRAP
    pos = np.empty_like(val)
    pos[0] = val[0]
    pos[1:] = val[0] + np.cumsum(d)
    return np.array(idx, np.int64), pos


def transfers(pos, min_mm=40.0):
    d = np.diff(pos)
    sp = np.convolve(np.abs(d).astype(float), np.ones(101) / 101,
                     mode="same") / 1e3
    moving = sp > 0.03
    out, i = [], 0
    while i < len(moving):
        if moving[i]:
            j = i
            while j < len(moving) and moving[j]:
                j += 1
            if abs(pos[j] - pos[i]) / 1e6 > min_mm:
                out.append((i, j))
            i = j
        else:
            i += 1
    return out


def cruise(pos, a, b, window=500):
    """Speed at the top of the trapezoid, from net travel over 1 s mid-move.

    Net displacement is the right quantity here: the AquadB link queues the
    increments it cannot deliver in one cycle rather than dropping them, so a
    one-second window carries the full travel even where single samples are
    pinned at the ceiling. It also avoids the acceleration ramps, which drag a
    whole-move average well below the commanded speed without anything being
    wrong, and it does not depend on where the move boundaries were placed.
    """
    m = (a + b) // 2
    if m - window < 0 or m + window >= len(pos):
        return float("nan")
    return abs(pos[m + window] - pos[m - window]) / 1e6 * (500.0 / window)


def old_cruise(path=OLD_SRC, tol=0.3):
    """The same measure on the CPU-timed run, whose log was not kept.

    Its profiles are recovered by clustering: the sequence steps through the
    commanded speeds in ascending order, so sorted clusters map onto the
    commanded list. Only the full-travel moves are used, to keep the homing
    crawl and the short repositioning moves out.
    """
    if not path.is_file():
        return {}
    _, pos = load(path)
    vs = sorted(c for a, b in transfers(pos, min_mm=50.0)
                if (c := cruise(pos, a, b)) > 1.0)
    groups = []
    for v in vs:
        if groups and v - groups[-1][-1] < tol:
            groups[-1].append(v)
        else:
            groups.append([v])
    return {cmd: float(np.mean(g))
            for cmd, g in zip((2.0, 5.0, 8.0), groups)}


def group(pos, runs):
    """Bucket the transfers onto 2 / 5 / 8 mm/s by their measured speed."""
    rows = {}
    for a, b in runs:
        v = abs(pos[b] - pos[a]) / 1e6 / ((b - a) / 1000.0)
        if v < 1.0:
            continue                      # homing crawl
        cmd = min((2.0, 5.0, 8.0), key=lambda c: abs(v - 0.95 * c))
        rows.setdefault(cmd, []).append((a, b, v))
    return rows


def main() -> int:
    if not SRC.is_file():
        print(f"no such file: {SRC}")
        return 2
    idx, pos = load()
    d = np.diff(pos).astype(float)
    rows = group(pos, transfers(pos))

    print(f"{SRC.name}: {len(idx):,} samples, {len(idx)/1000:.0f} s, "
          f"{int(np.sum(np.diff(idx) != 1))} gaps")
    old = old_cruise()
    print(f"{'cmd':>5} {'n':>2} {'cruise':>7} {'of cmd':>7} {'was':>7} "
          f"{'then':>6} {'at ceiling':>11} {'100ms max':>10}")
    stats = {}
    for cmd in sorted(rows):
        segs = rows[cmd]
        v = float(np.mean([s[2] for s in segs]))
        u = float(np.mean([cruise(pos, a, b) for a, b, _ in segs]))
        seg = np.concatenate([np.abs(d[a:b]) for a, b, _ in segs])
        clip = 100.0 * float(np.mean(seg == CEIL_NM))
        roll = max(np.convolve(np.abs(d[a:b]), np.ones(100) / 100,
                               mode="valid").max() for a, b, _ in segs)
        stats[cmd] = dict(v=v, u=u, clip=clip, roll=roll, segs=segs, steps=seg)
        was = old.get(cmd)
        print(f"{cmd:5.0f} {len(segs):2d} {u:7.3f} {100*u/cmd:6.2f}% "
              f"{was if was else float('nan'):7.3f} "
              f"{100*was/cmd if was else float('nan'):5.1f}% "
              f"{clip:10.2f}% {roll:10.0f}")

    over = int(np.sum(np.abs(d) > CEIL_NM))
    print(f"\nsamples above the ceiling: {over} (max {np.abs(d).max():.0f} nm)")
    print(f"  these pair with short neighbours - a 2-sample mean is "
          f"{np.mean([(abs(d[k])+abs(d[k+1]))/2 for k in np.where(np.abs(d)>CEIL_NM)[0] if k+1 < len(d)]):.0f} nm, "
          f"under the ceiling, so it is sample-clock jitter")

    style()
    fig = plt.figure(figsize=(11.6, 7.6))
    ax = fig.add_axes([0.070, 0.580, 0.380, 0.345])
    bx = fig.add_axes([0.570, 0.580, 0.395, 0.345])
    cx = fig.add_axes([0.070, 0.085, 0.380, 0.345])
    dx = fig.add_axes([0.570, 0.085, 0.395, 0.345])
    cmds = sorted(stats)

    # --- (a) did the fix work --------------------------------------------
    ax.plot([0, 9], [0, 9], color=GREEN, lw=1.3, ls=(0, (5, 3)),
            label="commanded")
    oc = sorted(old)
    if oc:
        ax.plot(oc, [old[c] for c in oc], "o-", color=INK3, lw=1.1, ms=7,
                mfc=SURFACE, mec=INK3, mew=1.4, label="CPU-timed (before)")
        for c in oc:
            ax.annotate(f"{100*old[c]/c:.0f}%", (c, old[c]), xytext=(7, -11),
                        textcoords="offset points", size=8.4, color=INK3)
    ax.plot(cmds, [stats[c]["u"] for c in cmds], "o-", color=RED, lw=1.4,
            ms=8, mfc=RED, mec=SURFACE, mew=1.1, label="RMT (after)")
    for c in cmds:
        ax.annotate(f"{100*stats[c]['u']/c:.1f}%", (c, stats[c]["u"]),
                    xytext=(7, 5), textcoords="offset points", size=8.4,
                    color=RED)
    ax.set_xlim(0, 9)
    ax.set_ylim(0, 9)
    ax.set_xlabel("commanded speed (mm/s)")
    ax.set_ylabel("cruise speed (mm/s)")
    ax.set_title("(a)  cruise speed: the step-timing fix", size=10, loc="left")
    ax.legend(frameon=False, fontsize=8.2, loc="upper left")
    ax.grid(True, axis="y")
    ax.grid(False, axis="x")

    # --- (b) step distribution against the ceiling ------------------------
    bins = np.arange(0, CEIL_NM + 100, 100)
    for c in cmds:
        bx.hist(stats[c]["steps"], bins=bins, histtype="step", lw=1.3,
                color=COLOUR[c], label=f"{c:.0f} mm/s commanded")
    bx.axvline(CEIL_NM, color=INK, lw=1.2, ls=(0, (4, 3)))
    bx.set_yscale("log")
    bx.set_xlim(0, CEIL_NM + 1500)
    bx.annotate("8333 nm\nceiling", (CEIL_NM, 2.2e3), xytext=(26, 0),
                textcoords="offset points", size=8.2, color=INK,
                ha="left", va="center")
    bx.set_xlabel("displacement per 1 ms sample (nm)")
    bx.set_ylabel("samples")
    bx.set_title("(b)  only 8 mm/s reaches the ceiling", size=10, loc="left")
    bx.legend(frameon=False, fontsize=8.2, loc="upper left")
    bx.grid(True, axis="y")
    bx.grid(False, axis="x")

    # --- (c) a 150 ms window inside the fastest move ----------------------
    a, b, _ = stats[8.0]["segs"][0]
    z0 = a + (b - a) // 2
    seg = np.abs(d[z0:z0 + 300])
    t = np.arange(len(seg))
    roll = np.convolve(seg, np.ones(100) / 100, mode="valid")
    cx.axhline(CEIL_NM, color=INK, lw=1.2, ls=(0, (4, 3)))
    cx.plot(t, seg, color=COLOUR[8.0], lw=0.9, marker="o", ms=2.0,
            label="per sample")
    cx.plot(t[99:], roll, color=INK, lw=1.6, label="100 ms mean")
    cx.annotate("8333 nm ceiling", (4, CEIL_NM), xytext=(0, 5),
                textcoords="offset points", size=8.2, color=INK)
    cx.set_xlim(0, 299)
    cx.set_ylim(6900, CEIL_NM + 420)
    cx.set_xlabel("time within the move (ms)")
    cx.set_ylabel("displacement per 1 ms (nm)")
    cx.set_title("(c)  8 mm/s: the ripple reaches the ceiling", size=10,
                 loc="left")
    cx.legend(frameon=False, fontsize=8.2, loc="lower right", ncol=2)
    cx.grid(True, axis="y")
    cx.grid(False, axis="x")

    # --- (d) how much headroom is left ------------------------------------
    xs = np.arange(len(cmds))
    dx.bar(xs, [stats[c]["roll"] for c in cmds], width=0.55,
           color=[COLOUR[c] for c in cmds], lw=0,
           label="sustained (100 ms max)")
    dx.axhline(CEIL_NM, color=INK, lw=1.3, ls=(0, (4, 3)), zorder=3)
    dx.text(-0.42, CEIL_NM + 260, "8333 nm ceiling", ha="left", size=8.2,
            color=INK)
    for i, c in enumerate(cmds):
        head = 100.0 * (1.0 - stats[c]["roll"] / CEIL_NM)
        top = stats[c]["roll"]
        dx.text(i, (CEIL_NM + 480 if top > CEIL_NM - 1200 else top + 230),
                f"{head:.0f}% headroom\n{stats[c]['clip']:.1f}% at ceiling",
                ha="center", va="bottom", size=8.0, color=INK2)
    dx.set_axisbelow(True)
    dx.set_xticks(xs)
    dx.set_xticklabels([f"{c:.0f} mm/s" for c in cmds], size=9)
    dx.set_ylabel("sustained rate (nm per 1 ms)")
    dx.set_ylim(0, CEIL_NM * 1.42)
    dx.set_title("(d)  headroom against the link", size=10, loc="left")
    dx.grid(True, axis="y")
    dx.grid(False, axis="x")

    OUT.mkdir(parents=True, exist_ok=True)
    png = OUT / "06_rmt_bandwidth.png"
    fig.savefig(png)
    fig.savefig(OUT / "06_rmt_bandwidth.pdf")
    plt.close(fig)
    print(f"\nwrote {png}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
