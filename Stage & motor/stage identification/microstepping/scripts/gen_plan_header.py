#!/usr/bin/env python3
"""Emit firmware/mres_test/mres_plan.h from sequence/mres_plan.csv.

Part 2 runs standalone on the board, so the sketch needs the plan compiled in.
Generating the header from the same CSV that mres_design.py writes keeps one
definition of the sequence: change the design, re-run mres_design.py, re-run
this, reflash. Editing the header by hand defeats the point.

    python scripts/mres_design.py        # -> sequence/mres_plan.csv
    python scripts/gen_plan_header.py    # -> firmware/mres_test/mres_plan.h
"""
from pathlib import Path
import csv
import datetime as dt

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "sequence" / "mres_plan.csv"
OUT = ROOT / "firmware" / "mres_test" / "mres_plan.h"

TAG_MAX = 23          # must match PlanRow::tag[] in the sketch
KINDS = {"move": 0, "stair": 1, "set_mres": 2}

SEGMENT_SHORT = {"reference": "REF", "end": "END"}


def tag_for(row: dict, index: int) -> str:
    seg = SEGMENT_SHORT.get(row["segment"], row["segment"].replace("block", "B"))
    phase = row["phase"] or row["tier"] or row["kind"]
    return f"{index:03d}_{seg}_{phase}"[:TAG_MAX]


def main() -> None:
    if not CSV.exists():
        raise SystemExit(f"missing {CSV} - run scripts/mres_design.py first")
    rows = list(csv.DictReader(CSV.open(newline="", encoding="utf-8")))
    rows = [r for r in rows if r["part"] == "stepping"]
    if not rows:
        raise SystemExit("no 'stepping' rows in the plan")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    total_s = float(rows[-1]["t_end"])
    body = []
    for i, r in enumerate(rows):
        kind = KINDS[r["kind"]]
        body.append(
            "  {{{:d}, {:>7d}, {:>3d}, {:>5d}, {:>4d}, {:>4d}, {:>3d}, {:>5d}, \"{}\"}},"
            "  // {}".format(
                kind, int(r["target"]), int(r["speed_fs"]),
                round(float(r["dwell_s"]) * 1000), int(r["mres"]),
                int(r["n_inc"]), int(r["inc_usteps"]),
                round(float(r["inc_dwell_s"]) * 1000),
                tag_for(r, i), r["label"][:40]))

    header = f"""/* GENERATED by scripts/gen_plan_header.py from sequence/mres_plan.csv.
 * Do not edit. Regenerate after changing mres_design.py.
 *
 * Generated {dt.datetime.now().strftime('%Y-%m-%d %H:%M')}
 * {len(rows)} rows, {total_s / 60:.1f} min, targets in u256 = 1/256 full step.
 *
 * Positions are relative to x_start, which part 1 puts at the centre of the
 * measured travel, on a full step.
 */
#pragma once
#include <stdint.h>

enum PlanKind : uint8_t {{ PLAN_MOVE = 0, PLAN_STAIR = 1, PLAN_SET_MRES = 2 }};

struct PlanRow {{
  uint8_t  kind;
  int32_t  target_u256;
  uint16_t speed_fs;
  uint32_t dwell_ms;
  uint16_t mres;
  uint16_t n_inc;
  uint16_t inc_usteps;
  uint32_t inc_dwell_ms;
  char     tag[{TAG_MAX + 1}];
}};

constexpr uint16_t MRES_PLAN_ROWS = {len(rows)};
constexpr uint32_t MRES_PLAN_SECONDS = {round(total_s)};

// kind, target_u256, speed_fs, dwell_ms, mres, n_inc, inc_usteps, inc_dwell_ms, tag
const PlanRow MRES_PLAN[MRES_PLAN_ROWS] = {{
{chr(10).join(body)}
}};
"""
    OUT.write_text(header, encoding="utf-8")
    kinds = {k: sum(1 for r in rows if r["kind"] == k) for k in KINDS}
    print(f"wrote {OUT}")
    print(f"  {len(rows)} rows ({kinds}), {total_s / 60:.1f} min")
    print(f"  targets {min(int(r['target']) for r in rows)} .. "
          f"{max(int(r['target']) for r in rows)} u256")
    print(f"  approx flash {len(rows) * (1 + 4 + 2 + 4 + 2 + 2 + 2 + 4 + TAG_MAX + 1)} bytes")


if __name__ == "__main__":
    main()
