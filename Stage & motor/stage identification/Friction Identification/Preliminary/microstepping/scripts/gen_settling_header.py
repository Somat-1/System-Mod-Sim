#!/usr/bin/env python3
"""Emit firmware/settling_test/settling_plan.h from sequence/settling_plan.csv.

The board runs the matrix standalone, so the plan is compiled in. Generating
the header from the same CSV settling_design.py writes keeps one definition:
change the design, re-run both, reflash. Editing the header by hand is
pointless - it is overwritten.

    python scripts/settling_design.py        -> sequence/settling_plan.csv
    python scripts/gen_settling_header.py    -> firmware/settling_test/settling_plan.h
"""
from pathlib import Path
import csv
import datetime as dt

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "sequence" / "settling_plan.csv"
OUT = ROOT / "firmware" / "settling_test" / "settling_plan.h"
TAG_MAX = 23
KINDS = {"move": 0, "set_mres": 1}


def tag_for(r: dict, i: int) -> str:
    d = (r["d_label"] or r["phase"]).replace(" ", "").replace("/", "")
    sign = "+" if int(r["direction"] or 0) > 0 else (
        "-" if int(r["direction"] or 0) < 0 else "")
    return f"{i:03d}_B{r['block']}_{r['phase']}_{d}{sign}"[:TAG_MAX]


def main() -> None:
    if not CSV.exists():
        raise SystemExit(f"missing {CSV} - run scripts/settling_design.py")
    rows = list(CSV.open(newline="", encoding="utf-8"))
    rows = list(csv.DictReader(rows))
    OUT.parent.mkdir(parents=True, exist_ok=True)

    body = []
    for i, r in enumerate(rows):
        body.append(
            "  {{{k}, {tgt:>8}, {spd:>4}, {dw:>5}, {mres:>4}, {d:>8}, "
            "{dir:>2}, {meas}, \"{tag}\"}},  // {label}".format(
                k=KINDS[r["kind"]], tgt=int(r["target_u256"]),
                spd=int(r["speed_fs"]),
                dw=round(float(r["dwell_s"]) * 1000), mres=int(r["mres"]),
                d=int(r["d_u256"]), dir=int(r["direction"] or 0),
                meas=int(r["measured"] or 0), tag=tag_for(r, i),
                label=r["label"][:38]))

    total_s = float(rows[-1]["t_end"])
    measured = sum(int(r["measured"] or 0) for r in rows)
    header = f"""/* GENERATED by scripts/gen_settling_header.py from
 * sequence/settling_plan.csv. Do not edit; regenerate after a design change.
 *
 * Generated {dt.datetime.now().strftime('%Y-%m-%d %H:%M')}
 * {len(rows)} rows, {measured} measured displacements, {total_s / 60:.1f} min.
 *
 * Positions are u256 = 1/256 full step, relative to x_start, which homing
 * puts at the centre of the measured travel on a full step. d_u256 is the
 * commanded displacement the row measures; the analysis compares it against
 * the settled difference either side of the move.
 */
#pragma once
#include <stdint.h>

enum PlanKind : uint8_t {{ PLAN_MOVE = 0, PLAN_SET_MRES = 1 }};

struct PlanRow {{
  uint8_t  kind;
  int32_t  target_u256;
  uint16_t speed_fs;
  uint32_t dwell_ms;
  uint16_t mres;
  int32_t  d_u256;      // commanded displacement, 0 when not a measurement
  int8_t   direction;
  uint8_t  measured;
  char     tag[{TAG_MAX + 1}];
}};

constexpr uint16_t PLAN_ROWS = {len(rows)};
constexpr uint16_t PLAN_MEASURED = {measured};
constexpr uint32_t PLAN_SECONDS = {round(total_s)};

// kind, target_u256, speed_fs, dwell_ms, mres, d_u256, direction, measured, tag
const PlanRow PLAN[PLAN_ROWS] = {{
{chr(10).join(body)}
}};
"""
    OUT.write_text(header, encoding="utf-8")
    print(f"wrote {OUT}")
    print(f"  {len(rows)} rows, {measured} measured, {total_s / 60:.1f} min")
    print(f"  approx flash {len(rows) * (1 + 4 + 2 + 4 + 2 + 4 + 1 + 1 + TAG_MAX + 1)} bytes")


if __name__ == "__main__":
    main()
